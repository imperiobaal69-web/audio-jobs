#!/usr/bin/env bash
# End-to-end load test on this machine: API + 4 worker processes (4 jobs each)
# against local Redis and Postgres. Three runs on identical inputs:
#   1. reference analyzer, 2. streaming analyzer, 3. streaming with repeated
#   recordings (result cache). State is reset before each run.
# Writes bench/results/load-*.json and docs/results/load-test.md.
set -euo pipefail
cd "$(dirname "$0")/.."
JOBS="${JOBS:-400}"
DURATION_MS="${DURATION_MS:-60000}"
CONCURRENCY="${CONCURRENCY:-32}"
WORKERS="${WORKERS:-4}"
export WORKER_CONCURRENCY="${WORKER_CONCURRENCY:-4}"
PSQL="psql -h 127.0.0.1 -p 5440 -U postgres -d audiojobs -qAt"
mkdir -p bench/results docs/results
go build -o bin/ ./cmd/...

reset() {
  scripts/run-local.sh stop >/dev/null
  bin/migrate >/dev/null 2>&1
  $PSQL -c "truncate jobs" >/dev/null
  redis-cli -p 6390 --scan --pattern 'aj:*' | xargs -r redis-cli -p 6390 del >/dev/null
  rm -rf .local/blobs
}

peak_rss_mb() { # sum of worker RSS, sampled until the file $1 exists
  local peak=0
  while [ ! -e "$1" ]; do
    local now
    now=$(ps -o rss= -p "$(cat .local/run/worker-*.pid | paste -sd, -)" 2>/dev/null | awk '{s+=$1} END {print int(s/1024)}')
    [ "${now:-0}" -gt "$peak" ] && peak=$now
    sleep 0.2
  done
  echo "$peak"
}

run() { # label analyzer distinct
  local label="$1" analyzer="$2" distinct="$3"
  reset
  ANALYZER="$analyzer" scripts/run-local.sh start "$WORKERS" >/dev/null
  rm -f .local/run/done
  peak_rss_mb .local/run/done >".local/run/rss" &
  bin/loadgen -api http://127.0.0.1:8088 -jobs "$JOBS" -concurrency "$CONCURRENCY" -duration-ms "$DURATION_MS" \
    -distinct "$distinct" -seed 42 -label "$label" -out "bench/results/load-$label.json" >/dev/null 2>.local/run/loadgen.err \
    || { cat .local/run/loadgen.err; exit 1; }
  touch .local/run/done
  wait
  local rss
  rss=$(cat .local/run/rss)
  python3 - "$label" "$rss" <<'PY'
import json, sys
label, rss = sys.argv[1], int(sys.argv[2])
p = f"bench/results/load-{label}.json"
r = json.load(open(p)); r["worker_peak_rss_mb"] = rss
json.dump(r, open(p, "w"), indent=2)
PY
  scripts/run-local.sh stop >/dev/null
  echo "$label done"
}

run reference reference 0
run streaming streaming 0
run streaming-cache streaming 40
reset

python3 - "$JOBS" "$DURATION_MS" "$WORKERS" "$WORKER_CONCURRENCY" "$CONCURRENCY" <<'PY'
import json, platform, subprocess, sys, datetime
jobs, dur, workers, wc, conc = sys.argv[1:]
rows = [json.load(open(f"bench/results/load-{l}.json")) for l in ("reference", "streaming", "streaming-cache")]
cpu = subprocess.run(["sysctl", "-n", "machdep.cpu.brand_string"], capture_output=True, text=True).stdout.strip()
out = [
  "# Load test results",
  "",
  "Generated by `scripts/load-test.sh`; do not edit by hand.",
  f"Run {datetime.datetime.now(datetime.timezone.utc):%Y-%m-%d %H:%M} UTC on one machine ({cpu}): API + {workers} worker processes x {wc} concurrent jobs,",
  f"local Redis and Postgres, {jobs} submissions of {int(dur)//1000}-second 16 kHz recordings from {conc} concurrent clients.",
  "This is a single-machine benchmark, not production traffic.",
  "",
  "| run | succeeded | cached | throughput (jobs/s) | e2e p50 (ms) | e2e p95 (ms) | e2e p99 (ms) | submit p99 (ms) | worker peak RSS (MB) | integrity failures |",
  "|---|---|---|---|---|---|---|---|---|---|",
]
for r in rows:
    out.append(f"| {r['label']} | {r['succeeded']}/{r['jobs']} | {r['cached']} | {r['throughput_jobs_per_sec']:.1f} | {r['e2e_p50_ms']} | {r['e2e_p95_ms']} | {r['e2e_p99_ms']} | {r['submit_p99_ms']} | {r['worker_peak_rss_mb']} | {r['integrity_failed']} |")
ref, st = rows[0], rows[1]
out += ["", f"Streaming vs reference analyzer: e2e p95 {ref['e2e_p95_ms']/max(st['e2e_p95_ms'],0.1):.1f}x lower, worker peak memory {ref['worker_peak_rss_mb']/max(st['worker_peak_rss_mb'],1):.1f}x lower.", ""]
open("docs/results/load-test.md", "w").write("\n".join(out))
print("\n".join(out))
PY
