#!/usr/bin/env bash
# Chaos test: steady load while worker processes are SIGKILLed and restarted
# every few seconds, attempts fail at random, and Redis is restarted without
# persistence (the whole queue is lost) partway through. Passes only if every
# job succeeds with a correct result. Writes docs/results/chaos.md.
set -euo pipefail
cd "$(dirname "$0")/.."
JOBS="${JOBS:-1000}"
RATE="${RATE:-40}"
KILL_EVERY="${KILL_EVERY:-2}"
KILL_WORKERS="${KILL_WORKERS:-1}"   # 0 = only restart Redis
JOB_TIMEOUT="${JOB_TIMEOUT:-4m}"
REDIS_RESTART_AT="${REDIS_RESTART_AT:-10}"
WORKERS=4
PSQL="psql -h 127.0.0.1 -p 5440 -U postgres -d audiojobs -qAt"
export WORKER_CONCURRENCY=4 VISIBILITY_TIMEOUT=4s SWEEP_EVERY=2s SWEEP_IDLE=6s \
  CHAOS_FAIL_RATE=0.05 CHAOS_PROCESS_DELAY="${CHAOS_PROCESS_DELAY:-500ms}" BACKOFF_BASE=200ms BACKOFF_MAX=2s MAX_ATTEMPTS=10
mkdir -p bench/results docs/results
go build -o bin/ ./cmd/...

scripts/run-local.sh stop >/dev/null
bin/migrate >/dev/null 2>&1
$PSQL -c "truncate jobs" >/dev/null
redis-cli -p 6390 --scan --pattern 'aj:*' | xargs -r redis-cli -p 6390 del >/dev/null
rm -rf .local/blobs .local/run/*.log
scripts/run-local.sh start "$WORKERS" >/dev/null

bin/loadgen -api http://127.0.0.1:8088 -jobs "$JOBS" -rate "$RATE" -concurrency 96 -duration-ms 10000 \
  -timeout "$JOB_TIMEOUT" -seed 7 -label chaos -out bench/results/chaos.json >/dev/null 2>.local/run/loadgen.err &
LOADGEN=$!

kills=0 redis_restarts=0 started=$(date +%s)
while kill -0 "$LOADGEN" 2>/dev/null; do
  sleep "$KILL_EVERY"
  kill -0 "$LOADGEN" 2>/dev/null || break
  if [ "$KILL_WORKERS" = 1 ]; then
    n=$((RANDOM % WORKERS + 1))
    kill -9 "$(cat .local/run/worker-$n.pid)" 2>/dev/null && kills=$((kills + 1))
    sleep 0.3
    scripts/run-local.sh worker "$n"
  fi
  if [ "$redis_restarts" -eq 0 ] && [ $(($(date +%s) - started)) -ge "$REDIS_RESTART_AT" ]; then
    redis-cli -p 6390 shutdown nosave >/dev/null 2>&1 || true
    sleep 1
    scripts/dev-up.sh >/dev/null
    redis_restarts=1
  fi
done
set +e
wait "$LOADGEN"
loadgen_exit=$?
set -e
elapsed=$(($(date +%s) - started))
scripts/run-local.sh stop >/dev/null

statuses=$($PSQL -c "select status || '=' || count(*) from jobs group by status order by status" | paste -sd' ' -)
attempts=$($PSQL -c "select coalesce(sum(attempts),0) || ' attempts for ' || count(*) || ' jobs; ' || count(*) filter (where attempts > 1) || ' jobs needed more than one' from jobs where not cached")
reclaimed=$(cat .local/run/worker-*.log | grep '"msg":"reclaimed abandoned deliveries"' | grep -o '"count":[0-9]*' | grep -o '[0-9]*$' | awk '{s+=$1} END {print s+0}' || true)
swept=$(cat .local/run/worker-*.log | grep '"msg":"re-enqueued stale jobs"' | grep -o '"count":[0-9]*' | grep -o '[0-9]*$' | awk '{s+=$1} END {print s+0}' || true)
lost=$(cat .local/run/worker-*.log | grep -c 'job was reclaimed by another worker' || true)
enqueue_fail=$(grep -c 'enqueue failed; sweeper will retry' .local/run/api.log || true)

python3 - "$kills" "$redis_restarts" "$elapsed" "$loadgen_exit" "$statuses" "$attempts" "${reclaimed:-0}" "${swept:-0}" "${lost:-0}" "${enqueue_fail:-0}" <<'PY'
import json, sys, datetime
kills, rr, elapsed, code, statuses, attempts, reclaimed, swept, lost, enq = sys.argv[1:]
r = json.load(open("bench/results/chaos.json"))
ok = code == "0" and r["succeeded"] == r["jobs"] and r["integrity_failed"] == 0
out = [
  "# Chaos test results",
  "",
  "Generated by `scripts/chaos.sh`; do not edit by hand.",
  f"Run {datetime.datetime.now(datetime.timezone.utc):%Y-%m-%d %H:%M} UTC on one machine: API + 4 worker processes, local Redis and Postgres.",
  "",
  "Faults injected while submitting {jobs} jobs at {rate}/s:".format(jobs=r["jobs"], rate="40"),
  "",
  f"- {kills} worker processes killed with SIGKILL (one every 2 s, each restarted under a new consumer name)",
  f"- {rr} Redis restart without persistence: stream, consumer group, pending deliveries, retries and cache all lost",
  "- 5% of attempts fail with an injected transient error; each attempt also takes an extra 500 ms, so kills land mid-job and",
  "  workers fall behind the 40/s arrival rate (16 slots x 2/s = 32 jobs/s): a backlog builds and the Redis restart destroys real queued work",
  "",
  "| outcome | value |",
  "|---|---|",
  f"| result | {'PASS' if ok else 'FAIL'} |",
  f"| jobs succeeded | {r['succeeded']} / {r['jobs']} |",
  f"| results failing integrity check | {r['integrity_failed']} |",
  f"| dead / timed out / submit errors | {r['dead']} / {r['timed_out']} / {r['submit_errors']} |",
  f"| final job states in Postgres | {statuses} |",
  f"| processing attempts | {attempts} |",
  f"| abandoned deliveries reclaimed from dead consumers | {reclaimed} |",
  f"| jobs re-enqueued from Postgres by the sweeper | {swept} |",
  f"| stale attempts discarded by lease fencing | {lost} |",
  f"| API enqueues that failed during the Redis outage | {enq} |",
  f"| end-to-end p50 / p99 (ms) | {r['e2e_p50_ms']} / {r['e2e_p99_ms']} |",
  f"| wall time (s) | {elapsed} |",
  "",
]
open("docs/results/chaos.md", "w").write("\n".join(out))
print("\n".join(out))
sys.exit(0 if ok else 1)
PY
